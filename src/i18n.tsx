const DICTS: Record<Lang, Dict> = { ru, en }
const STORAGE_KEY = 'bottleneck3d.lang'

function initialLang(): Lang {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY)
    if (saved === 'ru' || saved === 'en') return saved
  } catch {
    // Storage can be unavailable in embedded pages.
  }
  return navigator.language?.toLowerCase().startsWith('ru') ? 'ru' : 'en'
}

interface I18n {
  lang: Lang
  t: Dict
  setLang: (lang: Lang) => void
}

const I18nContext = createContext<I18n>({ lang: 'ru', t: ru, setLang: () => {} })

export function I18nProvider({ children, lang: forced }: { children: ReactNode; lang?: Lang }) {
  const [lang, setLangState] = useState<Lang>(() => forced ?? initialLang())
  setFormatLang(lang)
  const value = useMemo<I18n>(
    () => ({
      lang,
      t: DICTS[lang],
      setLang: (next) => {
        setFormatLang(next)
        setLangState(next)
        try {
          window.localStorage.setItem(STORAGE_KEY, next)
        } catch {
          // Not persisted; the choice still applies to this session.
        }
        document.documentElement.lang = next
      },
    }),
    [lang],
  )
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

// eslint-disable-next-line react-refresh/only-export-components
export function useI18n(): I18n {
  return useContext(I18nContext)
}
