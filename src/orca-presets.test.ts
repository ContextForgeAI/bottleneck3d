import { describe, expect, it } from 'vitest'
import { evaluateWorkload, parseGcodeText } from './analyzer'
import { DEFAULT_PRINTER_SETTINGS } from './domain/profile'
import {
  buildOrcaPresetLibrary,
  parseOrcaPreset,
  presetTimingChanges,
  resolveOrcaPreset,
  workloadWithPresets,
} from './orca-presets'

const file = (path: string, data: object) => ({ path, text: JSON.stringify(data) })

describe('Orca presets', () => {
  it('flattens arrays and drops meta keys', () => {
    const preset = parseOrcaPreset('user/default/machine/V.json', JSON.stringify({
      type: 'machine',
      name: 'V',
      inherits: 'Base',
      from: 'User',
      machine_max_acceleration_x: ['6000', '6000'],
      printable_height: '275',
    }))

    expect(preset?.kind).toBe('machine')
    expect(preset?.inherits).toBe('Base')
    expect(preset?.values).toEqual({
      machine_max_acceleration_x: '6000,6000',
      printable_height: '275',
    })
  })

  it('takes the kind from the folder when type is absent and ignores other JSON', () => {
    expect(parseOrcaPreset('a/filament/PLA.json', '{"name":"PLA"}')?.kind).toBe('filament')
    expect(parseOrcaPreset('a/Voron.json', '{"name":"Voron","version":"1"}')).toBeNull()
    expect(parseOrcaPreset('a/filament/x.info', 'sync_info = ')).toBeNull()
  })

  it('resolves inherits root-first and reports a missing system parent', () => {
    const library = buildOrcaPresetLibrary([
      file('user/default/filament/Mine.json', {
        type: 'filament', name: 'Mine', inherits: 'Parent', from: 'User',
        filament_max_volumetric_speed: ['23'],
      }),
      file('user/default/filament/Parent.json', {
        type: 'filament', name: 'Parent', inherits: 'Generic PLA @System', from: 'User',
        filament_max_volumetric_speed: ['12'], filament_diameter: ['1.75'],
      }),
      file('user_backup-v2.4.2/default/filament/Mine.json', {
        type: 'filament', name: 'Mine', filament_max_volumetric_speed: ['99'],
      }),
    ])
    const mine = library.presets.find((preset) => preset.name === 'Mine')!
    const resolved = resolveOrcaPreset(library, mine)

    expect(library.presets).toHaveLength(2)
    expect(resolved.chain).toEqual(['Mine', 'Parent'])
    expect(resolved.missingParent).toBe('Generic PLA @System')
    expect(resolved.config.filament_max_volumetric_speed).toBe('23')
    expect(resolved.config.filament_diameter).toBe('1.75')
  })

  it('reads a plugin export and prefers it over loose files', () => {
    const library = buildOrcaPresetLibrary([
      file('user/default/filament/Mine.json', {
        type: 'filament', name: 'Mine', inherits: 'Generic PLA @System',
        filament_max_volumetric_speed: ['23'],
      }),
      file('orca_plugins/bottleneck3d-presets.json', {
        format: 'bottleneck3d-orca-presets',
        presets: [
          { type: 'filament', name: 'Mine', from: 'User', filament_max_volumetric_speed: ['23'], filament_diameter: ['1.75'] },
          { type: 'machine', name: 'Voron 2.4 300 0.4 nozzle', from: 'system', machine_max_acceleration_x: ['20000', '20000'] },
        ],
      }),
    ])
    const mine = resolveOrcaPreset(library, library.presets.find((preset) => preset.name === 'Mine')!)

    expect(library.presets.map((preset) => preset.name).sort()).toEqual(['Mine', 'Voron 2.4 300 0.4 nozzle'])
    expect(mine.missingParent).toBeNull()
    expect(mine.config.filament_diameter).toBe('1.75')
  })

  it('lists only timing keys that differ from the file', () => {
    expect(
      presetTimingChanges(
        { machine_max_acceleration_x: '3000,3000', gcode_flavor: 'klipper' },
        { machine_max_acceleration_x: '6000,6000', gcode_flavor: 'klipper', nozzle_diameter: '0.4' },
      ),
    ).toEqual([{ key: 'machine_max_acceleration_x', file: '3000,3000', preset: '6000,6000' }])
  })

  it('machine limits from a preset change the estimate', () => {
    const workload = parseGcodeText([
      '; generated by OrcaSlicer 2.4.2',
      'G90', 'M83',
      'G1 X100 E5 F18000', 'G1 X0 E5', 'G1 X100 E5', 'G1 X0 E5',
      '; gcode_flavor = klipper',
      '; default_acceleration = 5000',
      '; machine_max_acceleration_extruding = 20000,20000',
      '; machine_max_acceleration_x = 20000,20000',
      '; machine_max_acceleration_y = 20000,20000',
    ].join('\n'))
    const library = buildOrcaPresetLibrary([
      file('user/default/machine/Slow.json', {
        type: 'machine', name: 'Slow', machine_max_acceleration_x: ['1000', '1000'],
      }),
    ])
    const slow = resolveOrcaPreset(library, library.presets[0])
    const settings = { ...DEFAULT_PRINTER_SETTINGS, acceleration: 5000, maxVolumetricFlow: 80 }

    const asFile = evaluateWorkload(workload, settings).estimatedSeconds
    const withSlow = evaluateWorkload(workloadWithPresets(workload, [slow]), settings).estimatedSeconds

    expect(withSlow).toBeGreaterThan(asFile * 1.2)
  })
})
